// 阻塞发送字符串
void UART1_SendString(char *str)
{
  HAL_UART_Transmit(&huart1, (uint8_t *)str, strlen(str), HAL_MAX_DELAY);
}
// 串口发送单个字节
HAL_StatusTypeDef UART1_SendByte(uint8_t data)
{
    return HAL_UART_Transmit(&huart1, &data, 1, HAL_MAX_DELAY);
}
// 注意：uint8_t 固定8位无符号整数
//      uint32_t 固定32位无符号整数

uint8_t UART1_ReceiveByte(uint32_t timeout)
{
  uint8_t byte;
  HAL_UART_Receive(&huart1, &byte, 1, timeout);
  return byte;
}
// 接收缓冲区
uint16_t UART1_ReceiveBuffer(uint8_t *buffer, uint16_t len, uint32_t timeout)
{
  HAL_UART_Receive(&huart1, buffer, len, timeout);
  return len;
}
